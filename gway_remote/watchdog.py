"""Local Raspberry Pi watchdog diagnostics and explicit root-only configuration.

No feature is enabled by installation or by read-only status checks.
This is not an MCP operation. The kernel/systemd remain the watchdog owners.
"""
from __future__ import annotations

import os
from pathlib import Path
import re
import subprocess
import tempfile

WATCHDOG_SYS = Path("/sys/class/watchdog")
DROPIN = Path("/etc/systemd/system.conf.d/90-gway-remote-watchdog.conf")
HEADER = "# Managed by gway-remote watchdog; do not edit this file manually.\n"
SETTING = "RuntimeWatchdogSec"
_EFFECTIVE = ("RuntimeWatchdogUSec", "RebootWatchdogUSec")
_TIMEOUTS = (15, 30, 60, 120)


def _read(path: Path) -> str | None:
    try:
        return path.read_text(encoding="utf-8").strip() or None
    except (OSError, UnicodeError, ValueError):
        return None


def _invoke(command: list[str], *, runner=subprocess.run):
    return runner(command, capture_output=True, text=True, check=False, timeout=5)


def inspect(*, root: Path = WATCHDOG_SYS, runner=subprocess.run) -> dict:
    """Report independently observed runtime state, never infer from device existence."""
    try:
        p = _invoke(["systemctl", "show", "--no-pager",
                     "--property=" + ",".join(_EFFECTIVE)], runner=runner)
        values = dict(line.split("=", 1) for line in p.stdout.splitlines()
                      if "=" in line and line.split("=", 1)[0] in _EFFECTIVE) if p.returncode == 0 else {}
    except (OSError, subprocess.TimeoutExpired, ValueError, AttributeError):
        values = {}
    try:
        paths = sorted(root.glob("watchdog*"))
    except (OSError, ValueError):
        paths = []
    devices = []
    for path in paths[:8]:
        if not re.fullmatch(r"watchdog[0-9]+", path.name):
            continue
        devices.append({"device": path.name,
                        "identity": _read(path / "identity"),
                        "state": _read(path / "state"),
                        "timeout_seconds": _number(path / "timeout"),
                        "timeleft_seconds": _number(path / "timeleft")})
    return {"status": "available" if devices else "unavailable",
            "runtime_watchdog_usec": values.get("RuntimeWatchdogUSec"),
            "reboot_watchdog_usec": values.get("RebootWatchdogUSec"),
            "devices": devices}


def _number(path: Path) -> int | None:
    value = _read(path)
    return int(value) if value and value.isascii() and value.isdecimal() else None


def format_watchdog(data: dict) -> str:
    rows = [f"Watchdog: {data['status']} (systemd runtime={data.get('runtime_watchdog_usec') or 'unknown'}; "
            f"reboot={data.get('reboot_watchdog_usec') or 'unknown'})"]
    for d in data["devices"]:
        rows.append(f"  {d['device']}: {d['identity'] or 'unknown'} "
                    f"state={d['state'] or 'unknown'} timeout={d['timeout_seconds']}s "
                    f"timeleft={d['timeleft_seconds']}s")
    return "\n".join(rows)


def configure(action: str, *, seconds: int | None = None, apply: bool = False,
              path: Path = DROPIN, root: Path = WATCHDOG_SYS,
              runner=subprocess.run, geteuid=os.geteuid) -> dict:
    """Only operator at root console may explicitly commit systemd manager changes.

    Drop-in is owned by this feature. Changes are atomically written; a failure
    to reexecute systemd restores the previous drop-in when possible.
    """
    if action not in {"enable", "disable"}:
        raise ValueError("action must be enable or disable")
    if action == "enable" and (type(seconds) is not int or seconds not in _TIMEOUTS):
        raise ValueError("enable requires --timeout-seconds (15, 30, 60, or 120)")
    if action == "disable" and seconds is not None:
        raise ValueError("disable takes no timeout")
    if not apply:
        raise ValueError("configuration requires explicit --apply")
    if geteuid() != 0:
        raise PermissionError("watchdog configuration requires root (run with sudo)")
    if action == "enable" and inspect(root=root, runner=runner)["status"] != "available":
        raise RuntimeError("no watchdog device found; refusing to enable")
    # Never overwrite a path owned by another application or follow symlinks.
    if path.is_symlink():
        raise RuntimeError("watchdog drop-in is a symlink")
    old = None
    if path.exists():
        if not path.is_file():
            raise RuntimeError("watchdog drop-in is not a regular file")
        old = path.read_text(encoding="utf-8")
        if not old.startswith(HEADER):
            raise RuntimeError("watchdog drop-in is not owned by gway-remote")
    contents = HEADER + "[Manager]\n" + SETTING + "=" + (
        str(seconds) + "s" if action == "enable" else "0"
    ) + "\n"
    path.parent.mkdir(parents=True, mode=0o755, exist_ok=True)
    _write_atomic(path, contents)
    try:
        _reexec(runner)
    except Exception:
        try:
            if old is None:
                path.unlink(missing_ok=True)
            else:
                _write_atomic(path, old)
            _reexec(runner)
        except Exception:
            # This must not mask the original failure; remediation requires console.
            pass
        raise
    return {"action": action, "configured_timeout_seconds":
            seconds if action == "enable" else 0,
            "watchdog": inspect(root=root, runner=runner)}


def _write_atomic(path: Path, contents: str) -> None:
    name = None
    try:
        with tempfile.NamedTemporaryFile("w", encoding="utf-8",
                                         dir=path.parent, prefix=".gway-watchdog-",
                                         delete=False) as stream:
            name = Path(stream.name)
            stream.write(contents)
            stream.flush()
            os.fsync(stream.fileno())
        os.chmod(name, 0o644)
        os.replace(name, path)
    finally:
        if name is not None:
            name.unlink(missing_ok=True)


def _reexec(runner) -> None:
    try:
        result = _invoke(["systemctl", "daemon-reexec"], runner=runner)
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise RuntimeError("systemd daemon-reexec failed") from exc
    if result.returncode:
        raise RuntimeError("systemd daemon-reexec failed")
